# Languages that fall back to a parent map then English for missing keys
_FALLBACK_CHAIN: dict[str, str] = {
    "pt": "pt_BR",
    "bg": "ru",
    "sr": "ru",
    "uk": "ru",
    "sk": "cs",
    "sl": "cs",
    "hr": "cs",
    "lt": "en",
    "lv": "en",
    "el": "en",
    "ca": "es",
    "sw": "en",
    "yo": "en",
    "pa": "hi",
    "ur": "ar",
}


def resolve_translations(code: str) -> dict[str, str]:
    """Prefer complete_maps.json (full parity with English); fall back to partials."""
    base = _base_map()
    # Full maps: same key count as English for every language
    try:
        from m3utolocal.i18n.complete_maps import map_for

        complete = map_for(code)
        merged = dict(base)
        merged.update(complete)
        return merged
    except Exception:
        pass
    if code in TRANSLATIONS:
        merged = dict(base)
        merged.update(TRANSLATIONS[code])
        return merged
    parent = _FALLBACK_CHAIN.get(code)
    if parent and parent in TRANSLATIONS:
        merged = dict(base)
        merged.update(TRANSLATIONS[parent])
        return merged
    return base


def escape_po(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
    )


def write_po(code: str, translations: dict[str, str]) -> Path:
    lang_dir = LOCALE_DIR / code / "LC_MESSAGES"
    lang_dir.mkdir(parents=True, exist_ok=True)
    po_path = lang_dir / f"{DOMAIN}.po"
    lines = [
        '# m3utolocal translation catalog',
        f'# Language: {code}',
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: m3utolocal 1.1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        f'"Language: {code}\\n"',
        '"MIME-Version: 1.0\\n"',
        "",
    ]
    # Plural forms are written separately as msgid/msgid_plural — exclude them here.
    plural_ids = {s for s, p in PLURALS} | {p for s, p in PLURALS}
    for msgid, msgstr in sorted(translations.items(), key=lambda x: x[0]):
        if msgid in plural_ids:
            continue
        lines.append(f'msgid "{escape_po(msgid)}"')
        lines.append(f'msgstr "{escape_po(msgstr)}"')
        lines.append("")
    for (sing, plur), (es, ep) in PLURALS.items():
        # keep English plural forms; translate if present in map
        ts = translations.get(sing, es)
        tp = translations.get(plur, ep)
        lines.append(f'msgid "{escape_po(sing)}"')
        lines.append(f'msgid_plural "{escape_po(plur)}"')
        lines.append(f'msgstr[0] "{escape_po(ts)}"')
        lines.append(f'msgstr[1] "{escape_po(tp)}"')
        lines.append("")
    po_path.write_text("\n".join(lines), encoding="utf-8")
    return po_path


def compile_mo(po_path: Path) -> Path:
    mo_path = po_path.with_suffix(".mo")
    subprocess.run(
        ["msgfmt", "-o", str(mo_path), str(po_path)],
        check=True,
    )
    return mo_path


def write_pot() -> Path:
    LOCALE_DIR.mkdir(parents=True, exist_ok=True)
    pot = LOCALE_DIR / f"{DOMAIN}.pot"
    lines = [
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: m3utolocal 1.1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        "",
    ]
    for msgid in sorted(MESSAGES):
        lines.append(f'msgid "{escape_po(msgid)}"')
        lines.append('msgstr ""')
        lines.append("")
    pot.write_text("\n".join(lines), encoding="utf-8")
    return pot


def main() -> int:
    pot = write_pot()
    print(f"Wrote {pot}")
    codes = [li.code for li in available_languages()]
    for code in codes:
        tr = resolve_translations(code)
        # Ensure every catalog msgid has a translation (fallback to English)
        for k, v in MESSAGES.items():
            tr.setdefault(k, v)
        po = write_po(code, tr)
        mo = compile_mo(po)
        try:
            from m3utolocal.i18n.complete_maps import IDENTITY_OK
        except Exception:
            IDENTITY_OK = frozenset({"m3utolocal", "ETA", "URL", "M3U: {path}",
                                     "{percent:.0f}% · {rate} · {eta}"})
        missing = [
            k for k, v in tr.items()
            if k in MESSAGES and v == MESSAGES[k] and code != "en" and k not in IDENTITY_OK
        ]
        n_msg = sum(1 for k in tr if k in MESSAGES)
        print(f"  {code}: {po.name} + {mo.name} ({n_msg}/{len(MESSAGES)} MESSAGES"
              f"{f', {len(missing)} still English' if missing else ''})")
    print(f"Built {len(codes)} locales under {LOCALE_DIR}")
    return 0


